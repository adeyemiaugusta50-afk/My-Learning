// Generates src/pieces.generated.ts from the Chessnut SVG pieces (Alexis Luengas, Apache-2.0).
// Usage (from ChessWeb/):  node tools/gen-pieces.mjs [path-to-svg-dir]
// Default source dir is the copy kept with the Android project: ../ChessApp/assets-src/chessnut
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = resolve(process.argv[2] ?? resolve(here, '../../ChessApp/assets-src/chessnut'))
const out = resolve(here, '../src/pieces.generated.ts')

const entries = []
for (const color of ['w', 'b']) {
  for (const type of ['K', 'Q', 'R', 'B', 'N', 'P']) {
    const svg = readFileSync(resolve(src, `${color}${type}.svg`), 'utf8')
    const inner = svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>')).trim()
    const fen = color === 'w' ? type : type.toLowerCase()
    entries.push(`  ${JSON.stringify(fen)}: ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 800" aria-hidden="true" focusable="false">${inner}</svg>`)},`)
  }
}
writeFileSync(out, `// GENERATED by tools/gen-pieces.mjs from the Chessnut SVG pieces - do not edit by hand.
// Chessnut piece set by Alexis Luengas, licensed under the Apache License 2.0 (see public/licenses/).
// Keys are FEN letters: upper case = white, lower case = black.
export const PIECE_SVG: Record<string, string> = {
${entries.join('\n')}
}
`)
console.log(`wrote ${out}`)
