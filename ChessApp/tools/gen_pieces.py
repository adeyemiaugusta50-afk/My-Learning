#!/usr/bin/env python3
"""Convert the Chessnut SVG pieces in assets-src/chessnut into Kotlin vector data.

Usage (from the ChessApp directory):  python3 tools/gen_pieces.py

The SVGs only use <g>, <path>, <circle> and <ellipse> with fill / stroke attributes (no transforms), so each shape
becomes (path data, fill colour, stroke colour, stroke width, cap, join, miter limit) in a 800x800 coordinate space.
Source art: Alexis Luengas, Apache License 2.0 (see assets-src/chessnut/LICENSE.txt).
"""
import pathlib
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "assets-src" / "chessnut"
OUT = ROOT / "app/src/main/java/com/casualchess/app/ui/PieceArt.kt"
NS = "{http://www.w3.org/2000/svg}"
INHERITED = ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "stroke-miterlimit")
DEFAULTS = {"fill": "#000", "stroke": "none", "stroke-width": "1", "stroke-linecap": "butt",
            "stroke-linejoin": "miter", "stroke-miterlimit": "4"}


def color(value):
    if value in (None, "none"):
        return "null"
    v = value.lstrip("#")
    if len(v) == 3:
        v = "".join(c * 2 for c in v)
    assert len(v) == 6, f"unsupported colour {value}"
    return f"0xFF{v.upper()}"


def num(x):
    return f"{float(x):g}"


def circle_path(cx, cy, rx, ry):
    cx, cy, rx, ry = map(float, (cx, cy, rx, ry))
    return (f"M{cx - rx:g},{cy:g}a{rx:g},{ry:g} 0 1,0 {2 * rx:g},0"
            f"a{rx:g},{ry:g} 0 1,0 {-2 * rx:g},0z")


def shapes(node, inherited):
    style = dict(inherited)
    for key in INHERITED:
        if key in node.attrib:
            style[key] = node.attrib[key]
    tag = node.tag.replace(NS, "")
    if tag == "path":
        yield node.attrib["d"], style
    elif tag == "circle":
        r = node.attrib["r"]
        yield circle_path(node.attrib["cx"], node.attrib["cy"], r, r), style
    elif tag == "ellipse":
        yield circle_path(node.attrib["cx"], node.attrib["cy"], node.attrib["rx"], node.attrib["ry"]), style
    for child in node:
        yield from shapes(child, style)


def kotlin_shape(d, st):
    cap = {"butt": "0", "round": "1", "square": "2"}[st["stroke-linecap"]]
    join = {"miter": "0", "round": "1", "bevel": "2"}[st["stroke-linejoin"]]
    return (f'        PieceShape("{d}", {color(st["fill"])}, {color(st["stroke"])}, '
            f'{num(st["stroke-width"])}f, {cap}, {join}, {num(st["stroke-miterlimit"])}f),')


def main():
    lines = [
        "// GENERATED by tools/gen_pieces.py from assets-src/chessnut/*.svg - do not edit by hand.",
        "// Chessnut piece set by Alexis Luengas, licensed under the Apache License 2.0.",
        "// See assets-src/chessnut/LICENSE.txt and LICENSES.md in the project root.",
        "package com.casualchess.app.ui",
        "",
        "/** One filled and/or stroked path in the 800 x 800 piece coordinate space. Colours are 0xAARRGGBB or null. */",
        "internal class PieceShape(",
        "    val pathData: String,",
        "    val fill: Long?,",
        "    val stroke: Long?,",
        "    val strokeWidth: Float,",
        "    /** 0 = butt, 1 = round, 2 = square. */",
        "    val cap: Int,",
        "    /** 0 = miter, 1 = round, 2 = bevel. */",
        "    val join: Int,",
        "    val miterLimit: Float,",
        ")",
        "",
        "internal const val PIECE_VIEWPORT = 800f",
        "",
        "/** Shapes per piece, keyed by FEN letter: uppercase = white (K Q R B N P), lowercase = black. */",
        "internal val PIECE_ART: Map<Char, List<PieceShape>> = mapOf(",
    ]
    for colour in "wb":
        for letter in "KQRBNP":
            svg = ET.parse(SRC / f"{colour}{letter}.svg").getroot()
            fen_char = letter if colour == "w" else letter.lower()
            lines.append(f"    '{fen_char}' to listOf(")
            for d, st in shapes(svg, DEFAULTS):
                lines.append(kotlin_shape(d, st))
            lines.append("    ),")
    lines.append(")")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
